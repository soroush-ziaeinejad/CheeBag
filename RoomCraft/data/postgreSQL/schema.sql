-- RoomCraft store schema. Safe to re-run: drops and recreates all tables.

DROP TABLE IF EXISTS reviews, shipments, payments, order_items, orders, customers, products;

CREATE TABLE products (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_asin      TEXT NOT NULL UNIQUE,
    source_url       TEXT,
    name             TEXT NOT NULL,
    full_title       TEXT,
    category         TEXT NOT NULL,
    description      TEXT,
    original_price   NUMERIC(10, 2),                     -- Amazon price, NULL if unknown
    price            NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    currency         CHAR(3) NOT NULL DEFAULT 'USD',
    image_url        TEXT,
    brand            TEXT,
    color            TEXT,
    material         TEXT,
    width_cm         NUMERIC(7, 1),
    depth_cm         NUMERIC(7, 1),
    height_cm        NUMERIC(7, 1),
    dimension_source TEXT,
    rating           NUMERIC(2, 1) CHECK (rating BETWEEN 0 AND 5),
    rating_count     INTEGER CHECK (rating_count >= 0),
    stock_quantity   INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  TEXT NOT NULL,
    last_name   TEXT NOT NULL,
    email       TEXT NOT NULL UNIQUE,
    phone       TEXT,
    address     TEXT,                                -- default shipping address
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE orders (
    order_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      INTEGER NOT NULL REFERENCES customers (customer_id),
    order_date       TIMESTAMPTZ NOT NULL DEFAULT now(),
    status           TEXT NOT NULL
                     CHECK (status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled')),
    total_amount     NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
    shipping_address TEXT,                                -- nullable: "missing address" is a test case
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    product_id    INTEGER NOT NULL REFERENCES products (id),
    quantity      INTEGER NOT NULL CHECK (quantity > 0),
    unit_price    NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),  -- price at purchase time
    UNIQUE (order_id, product_id)
);

CREATE TABLE payments (
    payment_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    amount                NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    payment_method        TEXT NOT NULL CHECK (payment_method IN ('credit_card', 'paypal', 'gift_card')),
    status                TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'refunded')),
    transaction_reference TEXT UNIQUE,                    -- simulated, never real card data
    paid_at               TIMESTAMPTZ
);

CREATE TABLE shipments (
    shipment_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           INTEGER NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    carrier            TEXT NOT NULL,
    tracking_number    TEXT,                              -- NULL until dispatched
    status             TEXT NOT NULL CHECK (status IN ('pending', 'in_transit', 'delivered')),
    shipped_at         TIMESTAMPTZ,
    estimated_delivery DATE,
    delivered_at       TIMESTAMPTZ
);

CREATE TABLE reviews (
    review_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        INTEGER NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    source_review_id  TEXT UNIQUE,                       -- Amazon review id; NULL for reviews written in our store
    rating            SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title             TEXT,
    body              TEXT NOT NULL,
    variation         TEXT,                              -- e.g. "Size: 32 Ounces Color: Black"
    helpful_count     INTEGER NOT NULL DEFAULT 0 CHECK (helpful_count >= 0),
    verified_purchase BOOLEAN NOT NULL DEFAULT FALSE,
    review_date       DATE NOT NULL DEFAULT current_date
);

-- Postgres does not index foreign keys automatically; these make "orders of customer X" fast.
CREATE INDEX ON orders (customer_id);
CREATE INDEX ON order_items (order_id);
CREATE INDEX ON payments (order_id);
CREATE INDEX ON shipments (order_id);
CREATE INDEX ON reviews (product_id);
