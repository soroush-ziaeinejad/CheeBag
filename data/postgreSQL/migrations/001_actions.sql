-- 001: actions CHEE proposes and the customer confirms, plus an audit log of order changes.
-- Safe to re-run. A fresh database runs it automatically (03_actions.sql in the compose files).
-- Existing database:
--   docker compose exec -T postgres psql -U cheebag -d cheebag -f /data/postgreSQL/migrations/001_actions.sql

-- One row per proposal. The token goes to the customer's browser only; we keep its SHA-256 hash.
CREATE TABLE IF NOT EXISTS pending_actions (
    action_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash          TEXT NOT NULL UNIQUE,
    customer_id         INTEGER NOT NULL REFERENCES customers (customer_id),
    action_type         TEXT NOT NULL CHECK (action_type IN ('cancel_order', 'create_order')),
    order_id            INTEGER REFERENCES orders (order_id),     -- NULL for create_order until it is confirmed
    payload             JSONB NOT NULL DEFAULT '{}',              -- what the confirmation card showed
    expected_status     TEXT,                                     -- order status when proposed
    expected_updated_at TIMESTAMPTZ,                              -- order version when proposed
    status              TEXT NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'confirmed', 'discarded', 'expired', 'failed')),
    result              JSONB,                                    -- outcome; returned again if confirm is repeated
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at          TIMESTAMPTZ NOT NULL,
    resolved_at         TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS pending_actions_customer_idx ON pending_actions (customer_id, status);

-- Every proposal, confirmation, discard and rejection, for the activity timeline and debugging.
CREATE TABLE IF NOT EXISTS order_events (
    event_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    INTEGER REFERENCES orders (order_id),
    customer_id INTEGER NOT NULL REFERENCES customers (customer_id),
    action_id   INTEGER REFERENCES pending_actions (action_id),
    event_type  TEXT NOT NULL CHECK (event_type IN (
                    'cancel_proposed', 'cancel_confirmed', 'cancel_discarded', 'cancel_rejected',
                    'order_proposed', 'order_created', 'order_discarded', 'order_rejected')),
    detail      JSONB NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_events_order_idx ON order_events (order_id, created_at);
